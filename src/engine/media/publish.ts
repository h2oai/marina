import { extname } from "node:path";
import { normalizeAssetMime } from "../../storage/asset-mime";
import type { EntityId } from "../../types";
import type { Engine } from "../engine";
import { ingestAsset } from "./asset-library";

const DEFAULT_IMAGE_EXT = ".png";
const DEFAULT_VIDEO_EXT = ".mp4";

interface StoreGeneratedAssetParams {
  engine: Engine;
  entityName: string;
  filename?: string;
  mimeType: string;
  data: Uint8Array;
  prompt: string;
  model: string;
  metadata?: Record<string, unknown>;
  id?: string;
}

export interface StoredAssetResult {
  id: string;
  filename: string;
  storageKey: string;
}

export async function storeGeneratedAsset({
  engine,
  entityName,
  filename,
  mimeType: reportedMime,
  data,
  prompt,
  model,
  metadata,
  id,
}: StoreGeneratedAssetParams): Promise<StoredAssetResult> {
  if (!engine.db) throw new Error("Database not configured — cannot store generated asset.");
  if (!engine.storage) throw new Error("Storage not configured — cannot store generated asset.");

  // The provider-reported type is a claim, not a fact: generated bytes are
  // stored under the same allowlist + magic-byte policy as uploads.
  const mimeType = normalizeAssetMime(reportedMime, data);
  const assetId = id ?? crypto.randomUUID();
  const safeFilename =
    filename?.trim() && filename.trim().length > 0
      ? filename.trim()
      : `${assetId}${inferExt(mimeType)}`;
  // Provenance columns (migration 168): prompt, model, provider, job and its
  // cost — the job's recorded estimate when the caller passed no charge.
  const jobId = typeof metadata?.jobId === "string" ? metadata.jobId : undefined;
  const costUsd =
    typeof metadata?.costUsd === "number"
      ? metadata.costUsd
      : jobId
        ? (engine.db.getMediaJob(jobId)?.cost_estimate ?? undefined)
        : undefined;
  const provider = typeof metadata?.provider === "string" ? metadata.provider : undefined;
  const { asset } = await ingestAsset(engine, {
    id: assetId,
    owner: entityName,
    filename: safeFilename,
    mime: mimeType,
    data,
    ext: inferExt(mimeType, safeFilename),
    origin: "generated",
    provenance: {
      prompt,
      model,
      ...(provider ? { provider } : {}),
      ...(jobId ? { jobId } : {}),
      ...(typeof costUsd === "number" ? { costUsd } : {}),
    },
    metadata: {
      origin: "generated",
      prompt,
      model,
      ...metadata,
    },
  });

  return { id: assetId, filename: safeFilename, storageKey: asset.storage_key };
}

interface PublishGeneratedAssetParams {
  engine: Engine;
  entityId: EntityId;
  entityName: string;
  assetId: string;
  nodeType: "image" | "video";
  prompt: string;
  model: string;
  canvasId?: string;
  summary?: string;
}

export interface PublishResult {
  canvasId: string;
  nodeId: string;
}

export function publishGeneratedAsset({
  engine,
  entityId,
  entityName,
  assetId,
  nodeType,
  prompt,
  model,
  canvasId,
  summary,
}: PublishGeneratedAssetParams): PublishResult {
  if (!engine.db) throw new Error("Database not configured — cannot publish generated asset.");

  const db = engine.db;
  const asset = db.getAsset(assetId);
  if (!asset) {
    throw new Error(`Asset ${assetId} not found — cannot publish.`);
  }

  const canvas =
    (canvasId ? db.getCanvas(canvasId) : null) ??
    db.ensureEntityCanvas(entityId, entityName, entityName);
  const targetCanvasId = canvas.id;

  const nodes = db.getNodesByCanvas(targetCanvasId);
  const maxY = nodes.reduce((acc, node) => Math.max(acc, node.y + node.height), 0);

  const nodeId = crypto.randomUUID();
  const now = Date.now();
  const data = {
    filename: asset.filename,
    mime: asset.mime_type,
    url: engine.storage?.resolve(asset.storage_key),
    title: asset.filename,
    author: entityName,
    prompt,
    model,
  };

  db.createNode({
    id: nodeId,
    canvasId: targetCanvasId,
    type: nodeType,
    x: 0,
    y: maxY + 20,
    assetId: assetId,
    data,
    creatorName: entityName,
  });

  engine.logEvent({
    type: "canvas_publish",
    entity: entityId,
    canvasId: targetCanvasId,
    nodeId,
    timestamp: now,
  });

  engine.logEvent({
    type: "feed_event",
    kind: nodeType === "video" ? "video_generated" : "image_generated",
    entity: entityId,
    ref: assetId,
    summary: summary ?? `${entityName} generated ${nodeType} "${asset.filename}" with ${model}`,
    payload: {
      canvasId: targetCanvasId,
      nodeId,
      assetId,
      model,
      prompt,
      mime: asset.mime_type,
      filename: asset.filename,
    },
    timestamp: now,
  });

  return { canvasId: targetCanvasId, nodeId };
}

function inferExt(mime: string, fallbackFilename?: string): string {
  const fallback = fallbackFilename ? extname(fallbackFilename) : "";
  if (mime.startsWith("image/")) {
    return fallback || DEFAULT_IMAGE_EXT;
  }
  if (mime.startsWith("video/")) {
    return fallback || DEFAULT_VIDEO_EXT;
  }
  return fallback || DEFAULT_IMAGE_EXT;
}
