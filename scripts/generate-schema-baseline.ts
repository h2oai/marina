import { Database } from "bun:sqlite";
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { BASE_SCHEMA, MIGRATIONS } from "../src/persistence/schema";
import { SCHEMA_BASELINE_VERSION } from "../src/persistence/schema-baseline";
import { MIGRATIONS as HISTORY } from "../src/persistence/schema-history";

// The baseline is the schema an EMPTY database has at SCHEMA_BASELINE_VERSION
// after the real upgrade path: every migration's SQL AND its data conversion
// (`apply`), one transaction per version with foreign keys on, as
// MarinaDB.runMigrations does. A hook is not assumed to be a no-op on empty
// data — migration 138's drops the historical outbox table.
if (HISTORY.at(-1)?.version !== SCHEMA_BASELINE_VERSION)
  throw new Error(
    `schema-history.ts ends at ${HISTORY.at(-1)?.version}, baseline is ${SCHEMA_BASELINE_VERSION}`,
  );

// Tables a migration seeds with rows, and how each column is reproduced at
// installation. A seeded row anywhere else fails generation: a per-database
// value (randomblob, unixepoch) must never be baked into the artifact.
const INSTALL_TIME = "(strftime('%s','now') * 1000)";
const SEEDED_TABLES: Readonly<Record<string, Readonly<Record<string, string>>>> = {
  shell_allowlist: { added_at: INSTALL_TIME },
};

// Replay only in a disposable database, never against an operator's world.
function replay(): Database {
  const db = new Database(":memory:");
  db.exec("PRAGMA foreign_keys=ON");
  db.exec(BASE_SCHEMA);
  for (const migration of MIGRATIONS.filter((m) => m.version <= SCHEMA_BASELINE_VERSION))
    db.transaction(() => {
      db.exec(migration.sql);
      migration.apply?.(db);
      db.run("INSERT OR REPLACE INTO schema_version (version) VALUES (?)", [migration.version]);
    })();
  return db;
}

const quote = (name: string) => `"${name.replaceAll('"', '""')}"`;
function dump(db: Database): string {
  const shadows = new Set(
    (db.query("PRAGMA table_list").all() as { name: string; type: string }[])
      .filter((table) => table.type === "shadow")
      .map((table) => table.name),
  );
  const objects = (
    db
      .query(
        "SELECT type, name, tbl_name, sql FROM sqlite_schema WHERE sql IS NOT NULL ORDER BY rowid",
      )
      .all() as { type: string; name: string; tbl_name: string; sql: string }[]
  ).filter((object) => !object.name.startsWith("sqlite_") && !shadows.has(object.tbl_name));
  const statements: string[] = [];
  for (const type of ["table", "index", "view", "trigger"])
    for (const object of objects.filter((o) => o.type === type)) statements.push(`${object.sql};`);
  // Migrations seed the command allowlist. Preserve every seed row, not just DDL.
  for (const table of objects.filter((o) => o.type === "table" && o.name !== "schema_version")) {
    const rows = db.query(`SELECT * FROM ${quote(table.name)}`).all() as Record<string, unknown>[];
    const install = SEEDED_TABLES[table.name];
    if (rows.length > 0 && !install)
      throw new Error(
        `Migration replay seeds ${rows.length} row(s) in ${table.name}; review how each column is reproduced at installation and list it in SEEDED_TABLES`,
      );
    for (const row of rows) {
      const columns = Object.keys(row);
      const values = columns.map((column) => {
        // These are installation timestamps, not generation timestamps.
        if (install?.[column]) return install[column];
        const value = row[column];
        if (value === null) return "NULL";
        if (typeof value === "number" || typeof value === "bigint") return String(value);
        if (typeof value === "string") return `'${value.replaceAll("'", "''")}'`;
        throw new Error(`Unsupported baseline seed value in ${table.name}.${column}`);
      });
      statements.push(
        `INSERT INTO ${quote(table.name)} (${columns.map(quote).join(", ")}) VALUES (${values.join(", ")});`,
      );
    }
  }
  statements.push(`INSERT INTO schema_version(version) VALUES (${SCHEMA_BASELINE_VERSION});`);
  return statements
    .join("\n\n")
    .replaceAll("\\", "\\\\")
    .replaceAll("`", "\\`")
    .replaceAll("${", "\\${");
}

const first = replay();
const second = replay();
try {
  const sql = dump(first);
  // Two independent replays must agree: nothing per-database survives in the artifact.
  if (dump(second) !== sql) throw new Error("Migration replay is not deterministic");
  const source = `// Copyright 2025-2026 H2O.ai, Inc.
// SPDX-License-Identifier: Apache-2.0

// Generated by scripts/generate-schema-baseline.ts: an empty database replayed through
// immutable migration history, data conversions included.
// Fresh databases install this atomically; existing databases replay pending upgrades.
export const SCHEMA_BASELINE_VERSION = ${SCHEMA_BASELINE_VERSION};
export const SCHEMA_BASELINE = \`
${sql}
\`;
`;
  const path = resolve(import.meta.dir, "../src/persistence/schema-baseline.ts");
  if (process.argv.includes("--check")) {
    if (readFileSync(path, "utf8") !== source)
      throw new Error(
        "Schema baseline differs from historical replay; run bun scripts/generate-schema-baseline.ts",
      );
    console.log(`Schema baseline ${SCHEMA_BASELINE_VERSION} matches historical replay.`);
  } else {
    writeFileSync(path, source);
    console.log(`Generated schema baseline ${SCHEMA_BASELINE_VERSION}.`);
  }
} finally {
  first.close();
  second.close();
}
